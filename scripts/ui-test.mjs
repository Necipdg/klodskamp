// Browsertest af brugerfladen og kontrollisten (headless Chromium, tasterne trykkes rigtigt):
// npx vite build && npx vite preview --port 4173 &  →  node scripts/ui-test.mjs
import { chromium } from 'playwright-core';
const [url = 'http://localhost:4173/', out = 'test-output'] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => m.type() === 'error' && !m.text().includes('ERR_TUNNEL') && errors.push(m.text()));
let fails = 0;
const ok = (c, msg) => { console.log(`${c ? '  ✓' : '  ✗'} ${msg}`); if (!c) fails++; };
const ev = (fn, arg) => page.evaluate(fn, arg);
const frames = async (n) => { const f0 = await ev(() => window.__kk.state().frames); await page.waitForFunction((f) => window.__kk.state().frames >= f, f0 + n, { timeout: 180000 }); };
const vis = (sel) => ev((s) => { const e = document.querySelector(s); return !!e && !e.classList.contains('hidden') && getComputedStyle(e).display !== 'none'; }, sel);

await page.goto(url);
await page.waitForFunction(() => !!window.__kk, null, { timeout: 60000 });
await frames(2);
console.log('Startskærm');
ok(await vis('#menu'), 'startskærmen vises');
ok((await ev(() => window.__kk.state().state)) === 'menu', 'tilstand = menu');
await page.click('text=Spil som angriber');
await frames(2);
ok(await vis('#intro'), 'styrings-kortet vises ved kampstart');
await page.click('text=Klik for at starte');
await frames(2);
ok((await ev(() => window.__kk.state().state)) === 'play', 'kampen er i gang efter klik');
ok(await vis('#hud'), 'HUD vises');

console.log('Køb');
await page.keyboard.press('KeyB');
await frames(2);
ok(await vis('#buy'), 'B åbner købsmenuen');
const m0 = await ev(() => window.__kk.game.human.money);
await page.keyboard.press('Digit2'); // riffel – for dyr
await frames(1);
ok((await ev(() => window.__kk.game.human.money)) === m0, 'for dyrt køb afvises, pengene er uændrede');
ok((await page.textContent('#buy .msg')).includes('ikke penge nok'), 'besked: ikke penge nok');
await page.keyboard.press('Digit3'); // vest 650
await frames(1);
ok((await ev(() => window.__kk.game.human.money)) === m0 - 650, 'vest købt for $650');
ok((await ev(() => window.__kk.game.human.armor)) === 100, 'vesten giver 100 i panser');
await page.keyboard.press('KeyB');
await frames(1);
ok(!(await vis('#buy')), 'B lukker købsmenuen');

console.log('Bygning og ødelæggelse');
await ev(() => { const g = window.__kk.game; g.phaseT = 0.01; });
await ev(() => window.__kk.fastForward(0.1));
ok((await ev(() => window.__kk.game.phase)) === 'live', 'runden er live');
await page.keyboard.press('KeyB');
await frames(1);
ok(!(await vis('#buy')), 'købsmenuen kan ikke åbnes efter købsfasen');
await ev(() => { const g = window.__kk.game, h = g.human; h.blocks = 2; h.body.pos = { x: 5.5, y: 1, z: 40.5 }; h.prevPos = { ...h.body.pos }; h.yaw = 0; h.pitch = -0.55; for (const b of g.bots.values()) b.p.input.fire = false; g.bots.clear(); });
await page.keyboard.press('Digit4');
await ev(() => window.__kk.fastForward(0.4));
await frames(2);
ok((await ev(() => window.__kk.game.human.slot)) === 'blocks', 'tast 4 vælger byggeblokke');
ok(await ev(() => window.__kk.view.fx.preview.visible), 'forhåndsvisning af blokken vises');
await page.screenshot({ path: `${out}/ui-build-preview.png` });
const placed = await ev(() => { const g = window.__kk.game; const t = g.buildTarget(g.human); return t; });
ok(placed && placed.valid, `gyldigt mål for blokken (${placed && placed.x},${placed && placed.y},${placed && placed.z})`);
await ev(() => { const h = window.__kk.game.human; h.input.fire = true; h.input.firePressed = true; window.__kk.fastForward(0.05); h.input.fire = false; });
ok((await ev(([x, y, z]) => window.__kk.game.world.get(x, y, z), [placed.x, placed.y, placed.z])) === 11, 'venstreklik placerer en sandsæk');
await ev(() => { const g = window.__kk.game, h = g.human; h.body.pos = { x: 10.5, y: 1, z: 11.5 }; h.prevPos = { ...h.body.pos }; h.yaw = 0; h.pitch = -0.7; });
await ev(() => window.__kk.fastForward(0.05));
const bad = await ev(() => { const g = window.__kk.game; return g.buildTarget(g.human); });
ok(bad && !bad.valid && bad.reason.includes('bombeområdet'), `ulovlig placering vises som rød: "${bad && bad.reason}"`);
await frames(2);
await page.screenshot({ path: `${out}/ui-build-invalid.png` });

console.log('Plant bomben med E');
await ev(() => { const g = window.__kk.game; const c = g.players.find((p) => p.hasBomb); if (c !== g.human) { c.hasBomb = false; g.human.hasBomb = true; g.bomb.carrier = 0; } const h = g.human; h.body.pos = { x: 10.5, y: 1, z: 11.5 }; h.prevPos = { ...h.body.pos }; });
await page.keyboard.down('KeyE');
await ev(() => window.__kk.fastForward(0.05));
await frames(1);
ok(await ev(() => window.__kk.game.human.action?.kind === 'plant'), 'E starter plantningen');
ok(await vis('#hud .progress'), 'fremskridtsbjælke for plantning vises');
await page.screenshot({ path: `${out}/ui-plant.png` });
for (let i = 0; i < 8; i++) await ev(() => window.__kk.fastForward(0.4));
await page.keyboard.up('KeyE');
ok((await ev(() => window.__kk.game.phase)) === 'planted', 'bomben er plantet');
await frames(2);
ok((await page.textContent('#hud .clock')).includes('BOMBEN ER PLANTET'), 'uret viser bombens nedtælling');
await page.screenshot({ path: `${out}/ui-planted.png` });
await ev(() => { for (let i = 0; i < 8; i++) window.__kk.fastForward(5); });
ok(await ev(() => window.__kk.game.lastRound?.reason === 'exploded' || window.__kk.game.round > 1), 'bomben eksploderer → angriberne vinder');

console.log('Tilskuer og kampens afslutning');
await ev(() => { const g = window.__kk.game; while (g.phase !== 'buy') window.__kk.fastForward(0.5); g.phaseT = 0.01; window.__kk.fastForward(0.1); g.damage(g.human, 999, 3, 'rifle', false, g.human.body.pos); window.__kk.fastForward(0.1); });
await frames(2);
ok(await vis('#hud .spec'), 'tilskuer-tekst vises, når man er død');
await page.screenshot({ path: `${out}/ui-spectate.png` });
await ev(() => { const g = window.__kk.game; g.score.A = 4; g.bots.clear(); for (const q of g.players.filter((q) => q.team === 'D')) g.damage(q, 999, 1, 'rifle', false, q.body.pos); window.__kk.fastForward(6); });
await frames(2);
ok((await ev(() => window.__kk.state().state)) === 'end', 'tilstand = slut');
ok(await vis('#matchend'), 'slutskærmen vises');
ok((await page.textContent('#matchend')).includes('SEJR'), 'slutskærmen viser SEJR');
await page.screenshot({ path: `${out}/ui-matchend.png` });
await page.click('text=Spil igen');
await frames(2);
ok(await vis('#intro'), 'Spil igen starter en ny kamp');
ok(await ev(() => window.__kk.game.score.A === 0 && window.__kk.game.round === 1), 'ny kamp: 0-0, runde 1');
await page.click('text=Klik for at starte');
await frames(1);
await ev(() => { const g = window.__kk.game; g.phaseT = 0.01; window.__kk.fastForward(0.1); g.score.D = 4; g.bots.clear(); for (const q of g.players.filter((q) => q.team === 'A')) g.damage(q, 999, 4, 'rifle', false, q.body.pos); window.__kk.fastForward(6); });
await frames(2);
ok((await page.textContent('#matchend')).includes('NEDERLAG'), 'nederlag vises når forsvarerne vinder');
await page.click('text=Hovedmenu');
await frames(2);
ok(await vis('#menu'), 'Hovedmenu går tilbage til startskærmen');

console.log('Pause og indstillinger');
await page.click('text=Indstillinger');
await frames(1);
ok(await vis('#pause'), 'indstillinger åbner');
await page.click('#pause .seg button:has-text("Lav")');
await frames(2);
ok(await ev(() => window.__kk.view.quality === 0), 'grafik kan sættes til Lav');
await page.click('#pause .seg button:has-text("Høj")');
await page.click('#pause >> text=Tilbage');
await frames(1);
ok(errors.length === 0, `ingen JavaScript-fejl (${errors.join(' | ')})`);
console.log(fails ? `\n${fails} FEJL` : '\nALT OK');
await browser.close();
process.exit(fails ? 1 : 0);
